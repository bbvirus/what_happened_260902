/**
 * Figma `Icon` 섹션 심볼 12개를 렌더링한다.
 * 크기는 Figma 원본과 같은 24 고정이며 `--spacing-24` 에서 내려온
 * `size-24` 유틸리티로 지정한다. `shrink-0` 은 flex 컨테이너 안에서
 * 그 고정 크기가 줄어들지 않게 하기 위한 것이다.
 *
 * 기본값은 장식용(`aria-hidden="true"`)이다. 이 섹션의 아이콘은 전부
 * 버튼·입력 필드·리스트 같은 텍스트 있는 컨트롤에 붙는 보조 표시이고,
 * 그 경우 아이콘을 스크린리더에 노출하면 라벨이 중복 읽힌다.
 * 아이콘이 유일한 의미 전달자인 자리에서는 호출부에서
 * `aria-hidden={false}` 와 `aria-label` 을 넘겨 덮어쓴다
 * (props 를 `aria-hidden` 뒤에 전개하므로 덮어쓰기가 가능하다).
 */
export function Icon({ name, color = 'primary', className = '', ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      className={['size-24 shrink-0', COLOR[color], className].filter(Boolean).join(' ')}
      {...props}
    >
      {PATHS[name]}
    </svg>
  );
}

