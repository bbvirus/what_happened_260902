/*
 * 아이디 필드에 들어온 값이 이메일 형식인지만 판정한다.
 *
 * 두 화면(`Login` · `SignIn`)이 같은 규칙과 같은 문구를 써야 해서 한 곳에 둔다.
 * 각 화면에 정규식을 복사하면 한쪽만 고쳐지는 순간 두 화면의 판정이 갈린다.
 *
 * 규칙은 **딱 이만큼이다** — 공백 없는 로컬부 @ 공백 없는 도메인, 도메인에 점 1개 이상.
 * RFC 5322 를 따라가지 않는 이유: 그 이상의 판정은 Supabase 와 메일 서버가 한다.
 * 여기서 막는 것은 "아이디 필드에 이메일이 아닌 것을 넣었다" 하나뿐이고,
 * 그보다 촘촘한 규칙은 요청에도 Figma 에도 없어서 지어내지 않는다 (원칙 1).
 */
export function isEmail(value: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}
